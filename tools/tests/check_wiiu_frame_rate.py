def main():
    pc = (ROOT / "src/pc/pc_main.c").read_text()
    window = (ROOT / "src/pc/gfx/gfx_gx2_window.cpp").read_text()
    game = (ROOT / "src/game/game_init.c").read_text()
    config = (ROOT / "src/pc/configfile.h").read_text()
    enum = config[config.index("enum WiiUFrameRate {"):]
    enum = enum[:enum.index("};") + 2]
    code = FIXTURE + enum + "\n" + function(window, "gfx_gx2_set_frame_rate")
    code += "\n".join(function(pc, name) for name in (
        "pc_get_render_frame_multiplier", "exec_display_list", "produce_one_frame"))
    code += function(game, "draw_fps_counter") + TEST
    with tempfile.TemporaryDirectory(prefix="wiiu-frame-rate-") as directory:
        cpp = Path(directory) / "frame.cpp"
        cpp.write_text(code)
        for high in (False, True):
            binary = str(Path(directory) / ("high" if high else "native"))
            flags = ["-DHIGH_FPS_PC=1"] if high else []
            subprocess.run(["g++", "-std=c++17", "-O2", "-fsanitize=address,undefined",
                            "-no-pie", *flags, str(cpp), "-o", binary], check=True)
            subprocess.run([binary], check=True, timeout=20)


if __name__ == "__main__":
    main()
