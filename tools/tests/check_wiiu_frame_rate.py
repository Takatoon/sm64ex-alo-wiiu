def function(source, name):
    match = re.search(r"^(?:static )?(?:inline )?[^;\n{}]+\b" + name + r"\([^;\n]*\)\s*\{", source, re.M)
    assert match, name
    brace = source.index("{", match.start())
    end, depth = brace + 1, 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[match.start():end]


