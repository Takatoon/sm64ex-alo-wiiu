"""Bake the supplied Nunito Bold TTF into a PNG atlas for the GamePad."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    cell_width, cell_height, columns = 36, 38, 16
    font = ImageFont.truetype(str(args.font), 30)
    alpha = Image.new("L", (columns * cell_width, 6 * cell_height))
    draw = ImageDraw.Draw(alpha)
    advances = []
    for index, code in enumerate(range(32, 127)):
        glyph = chr(code)
        x = (index % columns) * cell_width
        y = (index // columns) * cell_height
        draw.text((x + 2, y + 29), glyph, anchor="ls", font=font, fill=255)
        advances.append(round(font.getlength(glyph)))
    atlas = Image.new("RGBA", alpha.size, "white")
    atlas.putalpha(alpha)
    atlas.save(root / "textures/minimap/theme/nunito-bold.png", optimize=True)
    rows = ["    " + ", ".join(map(str, advances[i:i+16])) + "," for i in range(0, 95, 16)]
    header = root / "src/pc/gfx/wiiu_gamepad_nunito.inc.h"
    header.write_text(
        "// Generated by tools/build_gamepad_theme_font.py from Nunito Bold.\n"
        f"static constexpr int NUNITO_CELL_WIDTH = {cell_width};\n"
        f"static constexpr int NUNITO_CELL_HEIGHT = {cell_height};\n"
        f"static constexpr int NUNITO_COLUMNS = {columns};\n"
        "static const uint8_t g_nunito_advance[] = {\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
